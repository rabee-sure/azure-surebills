<li style="margin-bottom:10px;">كما قد تقوم الشركة بجمع سجل البحث والأنشطة الخاصة بالمستخدم على موقعها الإلكتروني، لتوفير محتوى يتماشى مع اهتمامات العملاء، ولتحسين استجابة نتائج البحث والطلبات المقدمة.</li>

<li style="margin-bottom:10px;">عند إجراء أي معاملات عبر موقع &quot;مدفوعات شور&quot; الإلكتروني، قد يُطلب من المستخدم إدخال معلومات بطاقة الائتمان أو بطاقة الخصم. وفي جميع الأحوال، يتم إرسال تفاصيل المعاملة من خلال خوادم مؤمّنة، ولا تقوم &quot;مدفوعات شور&quot; بحفظ أو تخزين هذه البيانات تحت أي ظرف. لهذا الغرض، تلتزم الشركة باستخدام شهادات (أس أس أل) SSL سارية، وتتوافق مع المتطلبات القانونية ولوائح البنك المركزي السعودي.</li>

<li style="margin-bottom:10px;">تجدر الإشارة إلى أن &quot;مدفوعات شور&quot; لا تملك حق الوصول إلى، ولا تستخدم، البيانات الشخصية مثل تفاصيل بطاقات الائتمان أو الخصم أو سجلات المعاملات المصرفية. تُعالج جميع المدفوعات من خلال خوادم خارجية على بوابة دفع آمنة لضمان حماية بيانات العملاء، وفي حال استخدام البيانات غير الشخصية مع البيانات الشخصية بشكل مترابط، فسيتم التعامل مع تلك البيانات كبيانات شخصية وفقًا للسياسات ذات الصلة.</li>

</ul>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">مشاركة البيانات الشخصية</h2>

<p style="margin:0 0 18px 0;text-align:right;">قد تشارك مدفوعات شور بياناتك الشخصية – حسب الضرورة – للأغراض التالية:</p>

<ul style="margin:0 0 36px 25px;padding:0;">

<li style="margin-bottom:10px;">وفقًا لسياسة مشاركة البيانات الصادرة عن مكتب إدارة البيانات الوطنية، تلتزم شركتنا بعدم مشاركة بياناتك الشخصية مع الجهات غير الحكومية، إلا في الحالات التي تكون فيها هذه الجهات مصرحًا لها بأداء خدمات محددة متفق عليها مسبقًا، أو بعد الحصول على موافقتك الصريحة. كما نؤكد أن يتم إدراج هذا الالتزام كشرط أساسي في جميع العقود لضمان التزام الجهات الشريكة بأنظمة حماية البيانات بموجب النظام.</li>

<li style="margin-bottom:10px;">قد يتم مشاركة بياناتك الشخصية الضرورية مع جهات حكومية او خاصة لأغراض محددة مبنية على أساس نظامي أو احتياج عملي مبرر يهدف إلى تحقيق مصلحة عامة او خاصة لك دون إلحاق أي ضرر بالمصالح الوطنية، أو أنشطة الجهات، أو خصوصية الأفراد، أو سلامة البيئة، ويستثنى من ذلك البيانات والجهات المستثناة بأوامر سامية.</li>

<li style="margin-bottom:10px;">الامتثال والاستجابة للأنظمة، وللوائح السارية، أو للإجراءات والمطالبات القانونية، أو الحكومية والأمنية، أو للامتثال لأمر من المحكمة، أو أمر الاستدعاء، أو مذكرة تفتيش، أو طلب إنفاذ القانون، أو إجراءات قانونية مماثلة، أو لحماية حقوقنا القانونية.</li>

<li style="margin-bottom:10px;">تنفيذ شروطنا وأي شروط وسياسات سارية أخرى، بما في ذلك لأغراض التحقيقات في المخالفات المحتملة أو الاشتباه في حدوث انتهاك للشروط والأحكام أو احتيال أو تعدي على الملكية الفكرية أو أي نشاط آخر قد يكون غير قانوني أو يعرضنا للمسؤولية القانونية.</li>

<li style="margin-bottom:10px;">لحماية حقوقنا وخصوصيتنا، أو ممتلكاتنا، أو أمان مستخدمينا، أو موقع شركة مدفوعات شور، وللكشف عن ومنع حالات التزوير والمسائل الأمنية والقانونية والأعطال التقنية والتعامل معها والتحقيق فيها، ولحماية حقوق، أو ملكية، أو سلامة مستخدمينا، أو الآخرين. وهذا يشمل تبادل البيانات مع الشركات والمنظمات الأخرى لأسباب مختلفة، مثل الحماية من الاحتيال والحد من مخاطر الائتمان.</li>

<li style="margin-bottom:10px;"><strong>لصالح شركاء الأعمال:</strong> قد يتم مشاركة بياناتك الشخصية لشركائنا من شركة مدفوعات شور الذين نقدم معهم الخدمات مع الأخذ في الاعتبار المتطلبات القانونية للإسناد. لتسهيل عملية الطلب وتنفيذ الطلبات على سبيل المثال وليس الحصر خدمات الدعم الفني أو معالجة بيانات عمليات المدفوعات الالكترونية.</li>

<li style="margin-bottom:10px;">عند مشاركة بياناتك الشخصية مع أي طرف ثالث، يتم الحرص على مشاركتها من خلال بيئة آمنة وموثوقة وفقاً للأنظمة واللوائح والسياسات ذات العلاقة، ونحن ملزمون باتخاذ خطوات إضافية لضمان حماية بياناتك من خلال توقيع اتفاقية لمشاركة البيانات بين شركة مدفوعات شور والجهات الأخرى، وفقاً لشروط وأحكام محددة متوافقة مع مبادئ مشاركة البيانات</li>

</ul>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">الإفصاح للغير والمواقع الالكترونية للغير</h2>

<p style="margin:0 0 18px 0;text-align:right;">تقوم شركة مدفوعات شور بالإفصاح عن البيانات الشخصية لشركائها الاستراتيجيين والشركات التابعة وفقًا لما يسمح به النظام المطبق أو طبقاً لمسوغ نظامي، ولن يتم مشاركة البيانات لأغراض غير تسويقية.</p>

<p style="margin:0 0 18px 0;text-align:right;">يجب أن يكون المستخدمون على دراية بأنه في ظروف محددة بموجب النظام، قد تكون الشركة ملزمة بالكشف عن البيانات الشخصية استجابةً لطلبات قانونية أو حكومية، ولا يحق للمستخدم المطالبة بتعويضات إلا في حال وقوع ضرر مباشر. كما تحتفظ الشركة بحق الإفصاح عن البيانات لأغراض تنفيذ الشروط والأحكام، أو لحماية الهوية والأمن، أو في حالة الاندماج أو إعادة الهيكلة أو الاستحواذ، علاوة على ذلك، قد تحتوي خدمات مدفوعات شور على إعلانات وروابط لمواقع أخرى، ولذا يُرجى الاطلاع على &quot;سياسة ملفات تعريف الارتباط&quot; الخاصة بالشركة لمزيد من المعلومات.</p>

<p style="margin:0 0 18px 0;text-align:right;">لا تقدم شركة مدفوعات شور بيانات شخصية للغير إلا في الحالات المحددة صراحة في هذه السياسة. إذا تطلبت مواقع إلكترونية تابعة لأطراف أخرى تقديم معلومات شخصية من المستخدم، فإن المستخدم يقر بتقديم هذه المعلومات طواعية، ويوافق على تعويض شركة مدفوعات شور عن أي مطالبات أو مسؤوليات قد تترتب على استخدام هذه البيانات من قبل تلك المواقع. ولتجنب أي مسؤولية، يحق لشركة مدفوعات شور استخدام أي من الأدوات التالية:</p>

<ul style="margin:0 0 36px 25px;padding:0;">

<li style="margin-bottom:10px;">أدوات تحليل بيانات المستخدم</li>

<li style="margin-bottom:10px;">أدوات التتبع والتحليل</li>

<li style="margin-bottom:10px;">أدوات مراقبة أداء الموقع</li>

</ul>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">التزام صاحب البيانات بالخصوصية</h2>

<p style="margin:0 0 18px 0;text-align:right;">يقع على صاحب البيانات الشخصية دور كبير في حماية بياناته والحفاظ عليها من خلال عدة إجراءات:</p>

<ul style="margin:0 0 36px 25px;padding:0;">

<li style="margin-bottom:10px;">الاطلاع الدائم على سياسة الخصوصية والشروط والأحكام المحدثة، وتحديث كافة البيانات الشخصية والتحكم في تفضيلات الخصوصية.</li>

<li style="margin-bottom:10px;">التحكم في التفضيلات التسويقية وتعديلها والتأكد من مصادر الروابط قبل فتحها والتحقق من أسم المرسل قبل فتح أي اشعارات أو روابط.</li>

<li style="margin-bottom:10px;">عدم الكشف عن كلمات المرور، أو رموز الأمان، أو معلومات الحساب، أو أي من البيانات الشخصية لأي شخص، أو الاستجابة لأي مكالمات أو مواقع تجمع بيانات شخصية دون التأكد من سلامة الاتصال علماً بأنه لن تقوم مدفوعات شور بالاستفسار عن تلك البيانات.</li>

<li style="margin-bottom:10px;">اختيار كيفية التعامل مع ملفات تعريف الارتباط &quot;الكوكيز&quot; وفهم كيفية عملها أو عمل تقنيات التتبع الأخرى.</li>

<li style="margin-bottom:10px;">تسجيل الخروج دائماً في نهاية جلستك خاصةً إذا كنت تستخدم أجهزة خاصة بشخص آخر أو في أماكن الإنترنت العامة.</li>

<li style="margin-bottom:10px;">مع التأكيد على إخلاء مسؤولية مدفوعات شور عن الوصول غير المشروع للبيانات الشخصية بسبب فشل صاحب البيانات الشخصية في الحفاظ على سرية بيانته الشخصية.</li>

</ul>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">حماية البيانات الشخصية</h2>

<p style="margin:0 0 18px 0;text-align:right;">تلتزم &quot;مدفوعات شور&quot; بتطبيق مجموعة متنوعة من إجراءات الأمان، بما في ذلك استخدام تقنيات التشفير والمصادقة لضمان حماية بياناتك الشخصية والحفاظ على سريتها، بحيث لا يمكن لأي طرف غير مصرح له الوصول إليها، لذلك نوصي باتخاذ كافة التدابير اللازمة لحماية بياناتك أثناء تصفح الإنترنت، وعدم مشاركة أي معلومات حساسة، مثل كلمات المرور أو رموز الأمان، مع أي جهة كانت. يُفضل تغيير كلمات المرور بشكل دوري، واستخدام مزيج من الأحرف والأرقام، والتأكد من استخدام متصفح آمن عند الاتصال بالإنترنت.</p>

<p style="margin:0 0 18px 0;text-align:right;">تقوم مدفوعات شور بتوجيه تعليمات إلى موظفيها وممثليها والشركات التابعة لها بانتظام بشأن سياسة الخصوصية والأمان والالتزام الصارم بأمان معايير وإجراءات الخصوصية داخليًا وعلى كامل مستويات الشركة. يتعامل فقط ممثلو مدفوعات شور المدربون بشكل خاص مع البيانات الشخصية، وتواكب مدفوعات شور التطورات والتعديلات على اللوائح ذات الصلة في المملكة العربية السعودية.</p>

<p style="margin:0 0 18px 0;text-align:right;">يُرجى الانتباه إلى أن موظفي &quot;مدفوعات شور&quot; لن يطلبوا منك أبدًا تقديم أي بيانات شخصية أو كلمات مرور أو معلومات بطاقات ائتمان لأي غرض كان. في حال تلقيك طلبًا كهذا، نوصي بعدم الاستجابة وعدم مشاركة أي معلومات، والتواصل معنا فورًا للإبلاغ عن هذه المحاولات، في حال إذا كنت تعتقد أن أمان حسابك قد تعرض للخطر، أو تشك في أن شخصًا آخر يستخدم حسابك دون إذن، فيرجى إخطارنا على الفور عبر قنوات الاتصال الرسمية لدينا.</p>

<p style="margin:0 0 18px 0;text-align:right;">قد تقوم مدفوعات شور بتحديث السياسات الخاصة بها من وقت لآخر. أي تعديل أو تحديث من هذا القبيل يصبح قابلاً للتطبيق على الفور. يُنصح المستخدمون بالتحقق بانتظام من السياسات على الموقع الإلكتروني وبشكل عام على المنصات الكترونية التي تديرها مدفوعات شور.</p>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">الإجراء المتخذ في حالة حدوث خرق للبيانات</h2>

<p style="margin:0 0 18px 0;text-align:right;">تقوم مدفوعات شور بإخطار المستخدمين خلال 72 ساعة كحد أقصى من علمها بأي حادث أو تدخل يؤدي إلى خرق البيانات، ويتم الإخطار عبر البريد الإلكتروني لضمان وصول المعلومات بسرعة وفعالية أو من أي وسيلة أخري متاحة للإبلاغ، مما يساعد المستخدمين على اتخاذ الإجراءات الوقائية اللازمة في الوقت المناسب، بالإضافة إلى تقديم دعمها الكامل للمستخدم الذي تم انتهاك بياناته الشخصية من أجل ممارسة خيارات التعويض الخاصة به ضد الخرق ومرتكبيه. من هذا المنطلق، من المفهوم أن مدفوعات شور لن تكون بأي شكل من الأشكال مسؤولة مالياً تجاه المستخدم، لأي سبب من الأسباب، باستثناء الحالة التي يكون فيها الخرق قد تسبب عمداً من قبل مدفوعات شور أو ممثليها.</p>

<p style="margin:0 0 18px 0;text-align:right;">في حال حدوث اختراق أو تسريب للبيانات الشخصية من خلال أي طرف ثالث فأن مدفوعات شور غير مسؤولة قانونياً عن هذه الحادثة ولا يمكن الرجوع بالحق القانوني على مدفوعات شور.</p>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">الإشعارات والرسائل التسويقية والتحذيرية</h2>

<p style="margin:0 0 18px 0;text-align:right;">كما ذُكر سابقًا فإن جمع بياناتك الشخصية يستخدم لتحسين جودة الخدمات وتجربة المستخدم ولأغراض تسويقية وترويجية، بمجرد تزويدنا بأي من بيانات التواصل الخاصة بك، فذلك يعد موافقة على تلقي الرسائل التسويقية أو الدعائية، في حال عدم رغبتكم في استلام أي رسائل تسويقية أو دعائية أو المشاركة في برامج تخصيص الإعلانات الدعائية، فأنه يمكنك إلغاء تلك الخاصية من خلال الموقع الالكتروني من خلال الصفحة الشخصية داخل الحساب أو النقر علي رابط &quot;إلغاء الاشتراك&quot; أسفل كل رسالة من  رسائل البريد الالكتروني أو عن طريق التواصل هاتفياً بمركز خدمة العملاء.</p>

<p style="margin:0 0 18px 0;text-align:right;">فيما يخص الإشعارات والرسائل التحذيرية فأنها تعتبر خدمة أساسية لا يمكن إيقافها إلا في حال توقف حسابك أو إنهاء العلاقة مع الشركة نظراً لاحتوائها على بيانات مهمة تخص حسابك أو إشعار بتأثر الخدمات المقدمة لكم من الشركة وعليه فأن هذه الرسائل تعد جزء أساسي من الخدمات المقدمة من طرفنا.</p>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">زيارة الموقع الالكتروني من خارج المملكة</h2>

<p style="margin:0 0 18px 0;text-align:right;">يقر و يوافق المستخدم ان استخدام الموقع الالكتروني لمدفوعات شور في كافة الأوقات خاضع لأنظمة المملكة العربية السعودية (النظام المطبق) عند زيارة الموقع الالكتروني لمدفوعات شور من خارج المملكة، سوف يتم جمع وتخزين بيانات المستخدم وفقا لسياسة الخصوصية هذه وسياسات مدفوعات شور الأخرى ذات العلاقة (مثل سياسية ملفات الارتباط الخاصة بمدفوعات شور) يقر ويفهم المستخدم ذلك دون توجيه أي ادعاءات بأن تشريعات حماية البيانات أو الأمن السيبراني قد تختلف في المملكة العربية السعودية عن الدولة التي يتم الدخول منها إلى الموقع.</p>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">نقل البيانات خارج الحدود الجغرافية للمملكة</h2>

<p style="margin:0 0 18px 0;text-align:right;">وفقًا للأنظمة المطبقة، سيتم تخزين بياناتك الشخصية ومعالجتها بطريقة آمنة داخل الحدود الجغرافية للمملكة العربية السعودية، وذلك لضمان المحافظة على السيادة الوطنية الرقمية لهذه البيانات ما لم تكن من حالات نقل أو معالجة البيانات خارج الحدود الجغرافية للمملكة والموضحة في المادة (التاسعة والعشرون) من نظام حماية البيانات الشخصية.</p>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">(ب) سياسة ملفات الارتباط</h2>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">ملفات تعريف الارتباط والتقنيات المشابهة</h2>

<p style="margin:0 0 18px 0;text-align:right;">ملفات تعريف الارتباط هي ملفات تُخزن على جهاز المستخدم عند زيارة مواقع إلكترونية معينة، وتُستخدم لتحسين تجربة التصفح، وتتبع الأنشطة، ودعم الأغراض التسويقية، وتعزيز وظائف الموقع. تُرسل هذه الملفات عادةً إلى الخادم الذي أنشأها، أو إلى خوادم في نفس النطاق، كما يمكن إرسالها إلى مواقع جهات خارجية (&quot;ملفات تعريف ارتباط الطرف الثالث&quot;). يمكن تعطيل ملفات تعريف الارتباط من إعدادات المتصفح، ولكن ذلك قد يؤثر على تجربة التصفح أو يمنع الوصول لبعض أجزاء الموقع، مثل إجراء المعاملات على موقع</p>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">دور ملفات تعريف الارتباط</h2>

<p style="margin:0 0 18px 0;text-align:right;">تستخدم مدفوعات شور ملفات تعريف الارتباط بشكل يتسم بالشفافية ونظامي من أجل:</p>

