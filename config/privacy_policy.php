<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">الاحتفاظ بالبيانات الشخصية</h2>

<p style="margin:0 0 18px 0;text-align:right;">تلتزم &quot;مدفوعات شور&quot; بمنح المستخدمين حق الوصول إلى بياناتهم الشخصية ونسخ منها عند الطلب، وتقتصر البيانات التي يتم جمعها على المعلومات المقدمة من المستخدم قبل إجراء أي معاملات. كما يُتاح للمستخدم تعديل بياناته الشخصية المحفوظة لدى الشركة.</p>

<p style="margin:0 0 18px 0;text-align:right;">تضمن &quot;مدفوعات شور&quot; دقة البيانات وتحديثها من طرفها وطرف العميل طيلة فترة تقديم الخدمات، مع الامتثال للأنظمة المعمول بها. ورغم اتخاذ التدابير الأمنية، لا يمكن ضمان الأمان الكامل على الإنترنت.</p>

<p style="margin:0 0 18px 0;text-align:right;">يتم الاحتفاظ بالبيانات وفقًا لتعليمات البنك المركزي السعودي الواردة في نظام المدفوعات وخدماتها، مع التأكيد على فاعلية حقوق صاحب البيانات وفقاً للأنظمة. أما بيانات الحسابات الموقوفة أو المحذوفة، فيتم الاحتفاظ بها لأغراض قانونية وتجارية لضمان الامتثال ومنع الاحتيال وتسوية النزاعات.</p>

