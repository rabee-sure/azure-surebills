<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">البيانات المقدمة بواسطة الغير</h2>

<p style="margin:0 0 18px 0;text-align:right;">قد تتم إحالة المستخدم أو تسجيله على الموقع الالكتروني من قبل طرف ثالث، مثل الوكيل. على هذا النحو، سيقدم المستخدم إلى الطرف الثالث وسيقدم الطرف الثالث إلى مدفوعات شور البيانات الشخصية المشار إليها في النقطة (أ) اعلاه.</p>

<p style="margin:0 0 18px 0;text-align:right;">قد يتم جمع بعض البيانات التقنية بشكل تلقائي كمعلومات عن المتصفح ونظام التشغيل المستخدم وعنوان بروتوكول الانترنت (IP Address) ومعرفات الجهاز الفريدة أو نوع الجهاز بمجرد وصولك إلى خدماتنا أو استخدامها ويتم جمع بيانات الموقع لفهم أنماط حركة مرور العملاء لتحسين جودة تجربة العميل أو لأغراض أمنية لحماية العملاء من الاحتيال، كما يتم جمع تفضيلات الموقع ومقدار الوقت المستغرق في تصفح صفحات الموقع بهدف تحسين تجربة العميل وزيادة إنتاجية الموقع.</p>

<p style="margin:0 0 18px 0;text-align:right;">عند تقديم الطلبات وبمجرد تزويدنا بالبيانات المطلوبة أو البيانات الائتمانية (المقدمة طواعية) فأنه يحق لشركة مدفوعات شور معالجة البيانات والتحقق منها من جهات خارجية موثوقة على سبيل المثال وليس الحصر: كالنفاذ الوطني الموحد (تمت بموافقة العميل) أو بيانات السجل التجاري من وزارة التجارة أو ممثليها والربط مع خدمة واثق (للتحقق من بيانات السجل التجاري).</p>

