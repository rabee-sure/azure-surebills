<li style="margin-bottom:10px;">علاوة على ذلك، يوفر الموقع ميزات إحالة الموقع إلى الغير، مثل الأصدقاء والعائلة (الغير). سيتم تخزين الأسماء وتفاصيل الاتصال وعناوين البريد الإلكتروني وأرقام الهواتف الخاصة بهؤلاء الغير وإدارتها وجمعها بواسطة مدفوعات شور لأغراض تقديم خدماتها والتسويق والإعلان وتخضع هذه الميزات لهذه السياسة.قد نتلقى معلومات عنك من خدمات أخرى من خلال شبكات التواصل الاجتماعي. على سبيل المثال وليس الحصر، نتلقى معلومات معينة من فيسبوك أو منصة إكس أو غيرها عند استخدام الخدمات لتسجيل الدخول إلى شركة مدفوعات شور كما قد يُشارك المُعلنون والمُطورين والناشرون والشركاء التابعين وأطراف ثالثة أخرى معلومات معنا أيضاً. قد نستخدم هذه البيانات للمساعدة على استهداف أو قياس أداء الإعلانات.</li>

</ul>

<h2 style="font-size:30px;font-weight:700;color:#1f2937;margin:40px 0 20px 0;">آلية جمع البيانات</h2>

<p style="margin:0 0 18px 0;text-align:right;">يتم جمع البيانات الشخصية عند قيام المستخدم بالتسجيل في الموقع الالكتروني لمدفوعات شور أو التسجيل في موقعنا، في وقت إجراء المعاملات أو في الوقت الذي تتم فيه إحالة المستخدم إلى موقع مدفوعات شور من قبل طرف ثالث.</p>

<p style="margin:0 0 18px 0;text-align:right;">قد يتم تصفح موقع مدفوعات شور، وفي بعض الحالات، صفحاتها المميزة بشكل مجهول؛ في مثل هذه الحالات، لا تتوفر بعض ميزات الموقع (على سبيل المثال وليس الحصر، قد لا يتمكن المستخدم من إجراء المعاملات على موقع مدفوعات شور إلا بعد إدخال اسم المستخدم وكلمة المرور وتسجيل الدخول إلى الموقع). يتم توفير جميع البيانات الشخصية التي تم جمعها واستخدامها وإدارتها بواسطة مدفوعات شور من قبل المستخدمين على أساس طوعي بالتفصيل التالي:</p>

<ul style="margin:0 0 36px 25px;padding:0;">

<li style="margin-bottom:10px;">البيانات الشخصية تستخدم في إبقاء المستخدم على إطلاع باخر مستجدات مدفوعات شور، الفعاليات والاخبار المنتجات والاستراتيجيات.</li>

<li style="margin-bottom:10px;">تستخدم البيانات الشخصية أيضا من اجل تطوير موقع مدفوعات شور بالإضافة إلى المنتجات والاستراتيجيات وفقا لتفضيلات وتجربة المستخدم. كما أن البيانات الشخصية تستخدم في تطوير استراتيجية مدفوعات شور للتسويق ومحتوى الدعاية ومع ذلك تستخدم أيضا في تطوير أمن الموقع الالكتروني وحماية المستخدمين ضد النصب والاحتيال والبرمجيات الضارة.</li>

<li style="margin-bottom:10px;">قد تستخدم البيانات الشخصية أيضاً في التأكد من هويتك، تحديد الخدمات الملائمة للمستخدم والمميزات التي تكون يحق للمستخدم الحصول عليها من خلال استخدام الموقع الالكتروني او القيام بالمعاملات من مدفوعات شور.</li>

<li style="margin-bottom:10px;">تستخدم البيانات الشخصية أيضاً لإرسال بيانات ومعلومات مهمة وإشعارات للمستخدمين مثل تغيير سياسات لوائح مدفوعات شور والاشعارات المتعلقة بالمعاملات التي يقوم المستخدم بها من خلال مدفوعات شور /أو الإشعارات المتعلقة بالحوادث غير المرغوبة مثل توقف/تعطل الموقع الالكتروني، محاولات الاحتيال من خلال الموقع الالكتروني، إلى أخره.</li>

<li style="margin-bottom:10px;">تستخدم البيانات الشخصية خلال تقديم الطلبات لتمكين مدفوعات شور تقديم خدماتها واستيفاء متطلباتها وتلبية بعض المتطلبات القانونية والتنظيمية. ولتقديم خدمات الدعم والتواصل معك والرد على أسئلتك واستفساراتك أو للتحقيق في انتهاك مشتبه به للشروط والأحكام الخاصة بنا، أو أي نشاط غير قانوني آخر..</li>

<li style="margin-bottom:10px;">تستخدم البيانات الشخصية لأغراض التدقيق المحاسبية الخاصة بمدفوعات شور، والأسواق المستهدفة والجمهور المستهدف والمعاملات الخاصة بذوق مجموعة معينة أو مجموعة مهنية. إذا تم نشر البيانات التي نتجت عن التدقيق المحاسبي الخاص بمدفوعات شور (إلا إذا ما أقتضى النظام المطبق غير ذلك)، لن يتم نشر أسم أو بيانات شخصية أخرى بواسطة مدفوعات شور وسوف تظهر هذه البيانات في الإحصاءات دون أن يكون الغرض منها أو استخدامها الكشف عن هوية شخص لأي سبب كان.</li>

<li style="margin-bottom:10px;">يمكن استخدام البيانات الشخصية لإدارة العروض والمسابقات ذات الصلة على الموقع الإلكتروني في الحالات التي يتم فيها الحصول على موافقة المستخدم. وفي حال رغب المستخدم في إلغاء الاشتراك من تلقي أي رسائل بريد إلكتروني أو محتويات إعلانية من شركة مدفوعات شور، فسيكون لديه خيار إلغاء الاشتراك من قائمة المراسلات الخاصة بالشركة، بالإضافة إلى الانسحاب من خدمات الرسائل النصية الأخرى.</li>

